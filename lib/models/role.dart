import 'team.dart';

/// چه نوع تصمیم/اقدام شبانه‌ای این نقش داره؛ موتور بازی بر این اساس
/// می‌فهمه چه UI ای رو براش نشون بده.
enum NightActionKind {
  none,
  sorkoobLeaderDecision, // مخصوص ولی‌فقیه: تصمیم شات یا سلاخی
}

/// نتیجه‌ی خلاصه‌شده‌ی استعلامِ هکر: «لایک» یعنی مثبت (نشونه‌ی عضویت در '
/// سرکوب)، «دیس‌لایک» یعنی منفی (بی‌گناه به‌حساب میاد).
enum InvestigationResult { like, dislike }

/// نوعِ اسلحه‌ای که شورشی به یه بازیکن می‌ده: جنگی (واقعی، محدود) یا
/// مشقی (بی‌اثر، نامحدود).
enum GunType { war, blank }

/// شیوه‌ی بازیِ رهبرِ موساد — شبِ اول یه‌بار انتخاب می‌شه و برای همیشه
/// همون می‌مونه: یا عملیاتِ ترور (حدسِ نقش رو سرکوب‌ها) یا عملیاتِ سری
/// (شاتِ ساده، مثلِ ولی‌فقیه ولی با زره تداخل داره نه سلاخی).
enum MossadPlaystyle { assassination, secretOperation }

/// تعریف کامل یه نقش: اسم، تیم، توضیح، عکس کارت، و پرچم‌های قابلیت‌های خاص.
/// چون نقش‌های این سناریو خیلی به‌هم متفاوت و بسیار جزئی‌ان، به‌جای یه
/// سیستم «قابلیت عمومی»، فیلدهای اختصاصی روی خودِ نقش تعریف می‌شن.
class GameRole {
  final String id;
  final String name;
  final String teamId;
  final String description;

  /// فعلاً عکس‌ها موقتاً حذف شدن (برای کم‌کردن حجم)؛ بعداً که همه‌ی
  /// نقش‌ها آماده شدن، یه‌جا اضافه می‌شن. تا اون‌موقع همیشه null ـه.
  final String? imageAsset;

  final NightActionKind nightAction;

  // ---- فیلدهای مخصوص ولی‌فقیه ----
  final bool alwaysShowsInnocent; // استعلامش همیشه منفیه
  final bool hasNightArmor; // زره در شب
  final bool canSlaughter; // قابلیت سلاخی داره؟

  // ---- فیلدِ مخصوص وزیر امور خارجه ----
  final bool canNegotiate; // قابلیت اغفال/مذاکره داره؟

  // ---- فیلدِ مخصوص رئیس قوه قضاییه ----
  final bool canIssueExecutionOrder; // قابلیت صدور حکم اعدام داره؟

  // ---- فیلدِ مخصوص دکتر ----
  final bool canHeal; // قابلیتِ نجاتِ شبانه داره؟

  // ---- فیلدِ مخصوص هکر ----
  final bool canInvestigate; // قابلیتِ استعلامِ شبانه داره؟

  // ---- فیلدِ مخصوص مبارزِ انقلابی ----
  final bool canRevolutionaryAct; // قابلیتِ اعدامِ انقلابی/سلاخی داره؟

  // ---- فیلدِ مخصوص وکیل ----
  final bool canRevive; // قابلیتِ جان‌بخشیِ یک‌بارمصرف داره؟

  // ---- فیلدِ مخصوص رپر معترض ----
  final bool canRecruitResistance; // قابلیتِ عضوگیریِ شبانه برای مقاومت داره؟

  // ---- فیلدِ مخصوص ژینا ----
  final bool disablesSorkoobNextNightOnDeath; // با حذف‌شدنش، شبِ بعد سرکوب قابلیتی نداره

  // ---- فیلدِ مخصوص شورشی ----
  final bool canArmPlayers; // قابلیتِ تقسیمِ اسلحه داره؟

  // ---- فیلدِ مخصوص بازجو خبرنگار ----
  final bool canInterrogate; // قابلیتِ بازجوییِ یک‌بارمصرف داره؟

  // ---- فیلدِ مخصوص وزیر اطلاعات ----
  final bool canAskIntelQuestion; // قابلیتِ سؤالِ اطلاعاتی داره؟

  // ---- فیلدِ مخصوص فرمانده نیروی انتظامی ----
  final bool canDetain; // قابلیتِ بازداشتِ شبانه داره؟

  // ---- فیلدِ مخصوص مزدور لباس شخصی ----
  final bool canAssassinate; // قابلیتِ ترور داره؟

  // ---- فیلدِ مخصوص قهرمان ملی ----
  final bool canGuarantee; // قابلیتِ تضمین/مصونیتِ رأی داره؟

  // ---- فیلدِ مخصوص رهبر موساد ----
  final bool canMossadAct; // شبِ اول انتخابِ شیوه، بعدش شب‌های زوج ترور یا شاتِ سری

  // ---- فیلدِ مخصوص فعال مدنی ----
  final bool canRequestReferendum; // یک‌بار در بازی، شبانه، درخواستِ رفراندوم

  // ---- فیلدِ مخصوص تحلیلگر سیاسی ----
  final bool canInvestigateIndependent; // شب‌های زوج: استعلامِ عضویتِ تیمِ مستقل

  // ---- فیلدِ مخصوص بمب‌گذار (فقط سناریوی مافیا) ----
  final bool canPlantBomb; // یک‌بار در بازی، شب: کارگذاریِ بمب + رمزِ ۱ تا ۴

  // ---- فیلدِ مخصوص محافظ (فقط سناریوی مافیا) ----
  // پدافندِ غیرفعال: اگه زودیاک با شاتِ عملیاتِ سری هدفش بگیره، به‌جای
  // اینکه خودش صدمه ببینه، زودیاک همون‌لحظه کاملاً حذف می‌شه. قابلیتِ
  // اصلیِ دیگه‌ش («فداشدن» برای خنثی‌سازیِ بمب) کاملاً به بمب‌گذار وابسته‌ست
  // و تو کنترلر با roleId چک می‌شه، نه یه فیلدِ جدا.
  final bool countersZodiacShot;

  // ---- فیلدِ مخصوص رهبر موساد ----
  // برخلافِ زره‌ی یک‌بارمصرفِ ولی‌فقیه (hasNightArmor)، این زره هیچ‌وقت
  // مصرف نمی‌شه: هر شب از نو فعاله، پس صاحبش با شاتِ شب (نه سلاخی) هرگز
  // از بازی خارج نمی‌شه.
  final bool hasPermanentNightArmor;

  /// فیلدِ عمومی (نه مخصوصِ یه نقشِ خاص): برای نقش‌هایی مثلِ «سلبریتی
  /// حکومتی» که عضوِ واقعیِ سرکوب‌ان ولی چند شبِ اول در استعلامِ هکر
  /// بی‌گناه نشون داده می‌شن. ۰ یعنی از همون شبِ اول واقعی و دقیق نشون
  /// داده می‌شه؛ عددِ N یعنی تا شبِ N (شامل خودش) دیس‌لایک، و از شبِ N+1
  /// به بعد نتیجه‌ی واقعی.
  final int investigationHiddenUntilNight;

  /// فیلدِ عمومی (فعلاً فقط «جاسوس» ازش استفاده می‌کنه): اگه رپر/اوشن
  /// این نقش رو هدف بگیره، به‌جای حذفِ رپر/اوشن، خودش هر شب (نه فقط
  /// شب‌های اولِ بازی) وارد تیمِ اوشن/مقاومت می‌شه — یه نفوذیِ دائمی و
  /// همیشگی. برخلافِ investigationHiddenUntilNight (که این محافظت رو
  /// فقط تا شبِ N می‌ده و از N+1 قطع می‌شه)، این هیچ‌وقت قطع نمی‌شه؛
  /// کاملاً مستقل از investigationHiddenUntilNight هم هست، پس می‌شه
  /// هم‌زمان از شبِ اول زیرِ استعلام لایکِ واقعی هم بزنه (جاسوس دقیقاً
  /// همین ترکیبه: علنی+لایک از شبِ اول، ولی نفوذیِ همیشگیِ اوشن).
  final bool alwaysInfiltratesResistance;

  // ---- فیلدِ مخصوص معشوقه (فقط سناریوی مافیا) ----
  // با حذف‌شدنِ صاحبِ این فیلد (از هر مسیرِ «معمولی» — رأی، شات، سلاخیِ
  // حرفه‌ای، یا سایدِ مستقل)، اگه پدرخوانده هنوز زنده باشه، شبِ بعد
  // پدرخوانده عصبانی می‌شه و می‌تونه ۲بار شات/سلاخی بزنه.
  final bool enragesGodfatherOnDeath;

  // ---- فیلدِ مخصوص ناتاشا (فقط سناریوی مافیا) ----
  // یک‌بار در کلِ بازی، شب: یه بازیکن رو تا پایانِ روزِ بعد ساکت می‌کنه
  // (نه صحبت، نه چالش‌گرفتن) — از همون silencedRoundNumber ی سیستمِ
  // انضباطی استفاده می‌کنه، فقط منبعش یه نقشه نه تصمیمِ گرداننده.
  final bool canSilence;

  // ---- فیلدِ مخصوص خرابکار (فقط سناریوی مافیا) ----
  // هر شب (نامحدود) یه نفر رو انتخاب می‌کنه؛ اگه همون بازیکن بعداً با
  // اسلحه‌ی جنگی شلیک کنه، تیر به خودش برمی‌گرده.
  final bool canSabotageGun;

  // ---- فیلدِ مخصوص افشاگر ----
  // اگه در روز (نه با شاتِ شب) از بازی خارج بشه، همون‌لحظه می‌تونه یه
  // نفر رو انتخاب کنه تا گرداننده مافیابودن/نبودنِ اون رو علناً اعلام کنه.
  final bool canDiscloseTeam;

  const GameRole({
    required this.id,
    required this.name,
    required this.teamId,
    required this.description,
    this.imageAsset,
    this.nightAction = NightActionKind.none,
    this.alwaysShowsInnocent = false,
    this.hasNightArmor = false,
    this.canSlaughter = false,
    this.canNegotiate = false,
    this.canIssueExecutionOrder = false,
    this.canHeal = false,
    this.canInvestigate = false,
    this.canRevolutionaryAct = false,
    this.canRevive = false,
    this.canRecruitResistance = false,
    this.disablesSorkoobNextNightOnDeath = false,
    this.canArmPlayers = false,
    this.canInterrogate = false,
    this.canAskIntelQuestion = false,
    this.canDetain = false,
    this.canAssassinate = false,
    this.canGuarantee = false,
    this.canMossadAct = false,
    this.canRequestReferendum = false,
    this.canInvestigateIndependent = false,
    this.canPlantBomb = false,
    this.countersZodiacShot = false,
    this.hasPermanentNightArmor = false,
    this.investigationHiddenUntilNight = 0,
    this.alwaysInfiltratesResistance = false,
    this.enragesGodfatherOnDeath = false,
    this.canSilence = false,
    this.canSabotageGun = false,
    this.canDiscloseTeam = false,
  });
}

